def _circle(g, cx, cy, r, ch):
    for y in range(N):
        for x in range(N):
            if (x - cx) ** 2 + (y - cy) ** 2 <= r * r:
                g[y][x] = ch


def _blank():
    return [["."] * N for _ in range(N)]


def _drawn():
    """Icons that are easier as circles than as typed grids."""
    out = {}
    g = _blank()
    _circle(g, 7.5, 7.5, 6.4, "s")
    _circle(g, 7.5, 7.5, 4.0, "c")
    g[4][5] = g[5][4] = "W"
    out["plate"] = g

    g = _blank()
    _circle(g, 5.0, 9.5, 3.9, "c")
    _circle(g, 11.0, 5.0, 2.6, "c")
    _circle(g, 11.5, 11.5, 1.6, "c")
    g[8][3] = g[7][4] = g[4][10] = "W"
    out["bubbles"] = g

    g = _blank()
    _circle(g, 7.5, 7.5, 6.4, "g")
    for x, y in ((4, 8), (5, 9), (6, 10), (7, 9), (8, 8), (9, 7), (10, 6), (11, 5)):
        g[y][x] = g[y - 1][x] = "W"
    out["check"] = g

    g = _blank()
    _circle(g, 7.5, 5.0, 4.2, "b")
    for y in range(9, 13):
        g[y][7] = g[y][8] = "p"
    _circle(g, 7.5, 13.0, 1.6, "p")
    g[3][5] = g[2][6] = "W"
    out["rattle"] = g

    g = _blank()  # flower with a red slash: "no fragrance"
    for cx, cy in ((7.5, 4.0), (7.5, 11.0), (4.0, 7.5), (11.0, 7.5)):
        _circle(g, cx, cy, 2.7, "p")
    _circle(g, 7.5, 7.5, 2.0, "y")
    for i in range(2, 14):
        g[i][15 - i] = g[i][14 - i] = "X"
    out["no-scent"] = g
    return out


def grids():
    out = {k: [list(row) for row in v.strip("\n").splitlines()] for k, v in GRIDS.items()}
    out.update(_drawn())
    for name, g in out.items():
        assert len(g) == N and all(len(r) == N for r in g), name
    return out


def _rgb(h):
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def render(g):
    im = Image.new("RGBA", (N, N), (0, 0, 0, 0))
    at = lambda x, y: g[y][x] if 0 <= x < N and 0 <= y < N else "."
    for y in range(N):
        for x in range(N):
            ch = g[y][x]
            if ch in FAMILIES:
                light, mid, dark = FAMILIES[ch]
                tone = light if at(x, y - 1) != ch else dark if at(x, y + 1) != ch or at(x + 1, y) != ch else mid
                im.putpixel((x, y), _rgb(tone) + (255,))
            elif ch in FLAT:
                im.putpixel((x, y), _rgb(FLAT[ch]) + (255,))
            elif ch == "." and any(at(x + dx, y + dy) not in ".K" for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                im.putpixel((x, y), INK + (255,))
    return im


def build():
    OUT.mkdir(parents=True, exist_ok=True)
    icons = {name: render(g) for name, g in grids().items()}
    for name, im in icons.items():
        im.save(OUT / f"{name}.png")
    cols, s, pad = 5, 8, 16
    rows = (len(icons) + cols - 1) // cols
    sheet = Image.new("RGBA", (cols * (N * s + pad) + pad, rows * (N * s + pad) + pad), (236, 233, 228, 255))
    for i, im in enumerate(icons.values()):
        sheet.alpha_composite(im.resize((N * s, N * s), Image.NEAREST),
                              (pad + (i % cols) * (N * s + pad), pad + (i // cols) * (N * s + pad)))
    sheet.save(OUT / "gallery.png")
    print(f"{len(icons)} icons -> {OUT}")


if __name__ == "__main__":
    build()
