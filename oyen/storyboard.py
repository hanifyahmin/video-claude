"""Storyboard for a video's storyline: a PNG sheet + STORYLINE.md.

`python3 -m oyen storyboard videos/<name>` writes into videos/<name>/storyboard/.
Thumbnails come from the storyline's `source` footage at each beat's `src`
time; beats without one get a plain panel.
"""
import subprocess
import tempfile
from pathlib import Path

from PIL import Image, ImageDraw

from .character import POSE_SPECS, POSES
from .render import font, to_image
from .storyline import load

THUMB_W, THUMB_H = 360, 640


def _thumb(source, t, tmp):
    if source is None or t is None or not Path(source).exists():
        return Image.new("RGB", (THUMB_W, THUMB_H), (60, 64, 72))
    out = Path(tmp) / f"{t}.png"
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-ss", str(t), "-i", str(source), "-frames:v", "1",
                    "-vf", f"scale={THUMB_W}:{THUMB_H}:force_original_aspect_ratio=increase,"
                           f"crop={THUMB_W}:{THUMB_H}", str(out)], check=True)
    return Image.open(out).convert("RGB")


def _wrap(d, text, f, width):
    lines, cur = [], ""
    for w in text.split():
        t = (cur + " " + w).strip()
        if d.textlength(t, font=f) > width:
            lines.append(cur)
            cur = w
        else:
            cur = t
    return lines + [cur] if cur else lines


def render_png(story, video_dir, out_path, cols=4):
    f_time, f_label, f_bubble, f_note, f_title = font(30), font(24), font(18, mono=True), font(19), font(52)
    pad, card_h = 24, THUMB_H + 150
    rows = (len(story.beats) + cols - 1) // cols
    img = Image.new("RGB", (pad + cols * (THUMB_W + pad), 110 + rows * (card_h + pad)), (17, 19, 24))
    d = ImageDraw.Draw(img)
    d.text((pad, 28), f"Storyline Oyen — {story.title}", font=f_title, fill=(255, 214, 10))
    source = Path(video_dir) / story.source if story.source else None
    with tempfile.TemporaryDirectory() as tmp:
        for i, b in enumerate(story.beats):
            x0, y0 = pad + (i % cols) * (THUMB_W + pad), 110 + (i // cols) * (card_h + pad)
            img.paste(_thumb(source, b.src, tmp), (x0, y0))
            d.rectangle((x0, y0, x0 + THUMB_W, y0 + 44), fill=(0, 0, 0))
            when = f"{b.start:g}–{b.end:g}s"
            d.text((x0 + 10, y0 + 7), when, font=f_time, fill=(255, 214, 10))
            d.text((x0 + 26 + d.textlength(when, font=f_time), y0 + 10), f"· {b.scene}", font=f_note, fill=(255, 255, 255))
            spr = to_image(POSES[b.pose], 4)
            sx, sy = x0 + 6, y0 + THUMB_H - spr.height - 6
            img.paste(spr, (sx, sy), spr)
            if b.line:
                bx, by = sx + spr.width + 6, sy + 22
                bw = min(d.textlength(b.line, font=f_bubble) + 16, x0 + THUMB_W - 6 - bx)
                d.rectangle((bx - 3, by - 3, bx + bw + 3, by + 33), fill=(42, 22, 11))
                d.rectangle((bx, by, bx + bw, by + 30), fill=(255, 253, 245))
                d.text((bx + 8, by + 5), b.line, font=f_bubble, fill=(42, 22, 11))
            d.rectangle((x0, y0 + THUMB_H, x0 + THUMB_W, y0 + card_h), fill=(255, 248, 235))
            d.text((x0 + 12, y0 + THUMB_H + 12), f"Postur: {b.pose}", font=f_label, fill=(42, 22, 11))
            for j, ln in enumerate(_wrap(d, b.note, f_note, THUMB_W - 24)[:4]):
                d.text((x0 + 12, y0 + THUMB_H + 50 + j * 25), ln, font=f_note, fill=(90, 70, 55))
    img.save(out_path)
    return out_path


def render_markdown(story):
    used = {b.pose for b in story.beats}
    rows = "\n".join(f"| {b.start:.2f}–{b.end:.2f} | {b.scene} | {b.pose} | {b.line or '—'} | {b.note} |"
                     for b in story.beats)
    unused = ", ".join(p for p in POSE_SPECS if p not in used) or "—"
    return f"""# Storyline Oyen — {story.title}

Generated by `python3 -m oyen storyboard` from `storyline.py`; edit that file, not this one.

| Masa (s) | Babak | Postur | Dialog Oyen | Nota |
|---|---|---|---|---|
{rows}

Kelip mata: {", ".join(f"{t:g}s" for t in story.blinks) or "—"} · Lompat: {", ".join(f"{t:g}s" for t in story.jumps) or "—"}

Postur tidak digunakan: {unused}
"""


def render(video_dir):
    video_dir = Path(video_dir)
    story = load(video_dir)
    out = video_dir / "storyboard"
    out.mkdir(exist_ok=True)
    png = render_png(story, video_dir, out / "oyen-storyboard.png")
    (out / "STORYLINE.md").write_text(render_markdown(story))
    return png
